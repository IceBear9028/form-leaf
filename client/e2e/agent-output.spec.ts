import { test, expect, _electron as electron, type ElectronApplication } from "@playwright/test";
import electronPath from "electron";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomUUID } from "node:crypto";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
import { DocumentRepository } from "../src/main/document/documentRepository.ts";
import { AccessPolicy, emptyGrants } from "../src/main/mcp/accessPolicy.ts";
import { agentDocument } from "../test/fixtures/agent-document.mjs";

test("F06/F07: hidden revision PNG·PDF·외부 resource 차단·IME 보존·권한 폐기", async ({}, testInfo) => {
  test.setTimeout(120_000);
  const temporary = await mkdtemp(join(tmpdir(), "formleaf-agent-output-e2e-"));
  const userData = join(temporary, "user-data"); const workspace = join(userData, "workspaces");
  const repository = new DocumentRepository(workspace); const created = await repository.create();
  const fixture = agentDocument(created.document); fixture.name = "MCP 출력 테스트";
  fixture.nodes.markdown.source = "## Snapshot title 한글\n\n![외부 이미지](https://example.invalid/image.png)\n\n" + Array.from({ length: 80 }, (_, i) => `문단 ${i + 1}: saved revision content`).join("\n\n");
  fixture.nodes.markdown.visible = true; fixture.nodes.repeater.items[0].visible = true;
  await repository.save(fixture.documentId, fixture);
  const policy = new AccessPolicy(workspace); await policy.initialize(); const { connection, token } = await policy.create("출력 에이전트");
  await policy.setGrants(connection.id, { ...emptyGrants(), documentIds: [fixture.documentId], write: true, render: true }); await policy.setEnabled(true);
  const client = new Client({ name: "output-e2e", version: "1" }); let app: ElectronApplication | undefined;
  try {
    app = await electron.launch({ executablePath: electronPath as unknown as string, args: ["."], cwd: process.cwd(), env: { ...process.env, DOCUMENT_USER_DATA_DIRECTORY: userData, DOCUMENT_E2E_HEADLESS: "1" } });
    const page = await app.firstWindow(); await page.getByRole("button", { name: /MCP 출력 테스트/ }).click();
    await client.connect(new StreamableHTTPClientTransport(new URL("http://127.0.0.1:32516/mcp"), { requestInit: { headers: { Authorization: `Bearer ${token}` } } })); await client.listTools();
    const read = (await client.callTool({ name: "get_document", arguments: { documentId: fixture.documentId } })).structuredContent as any;
    const changed = (await client.callTool({ name: "apply_operations", arguments: { documentId: fixture.documentId, expectedRevision: read.data.revision, requestId: randomUUID(), operations: [{ type: "update_node_style", nodeId: "text", patch: { typography: { fontSizePt: 18, color: { kind: "hex", value: "#123456" } } } }] } })).structuredContent as any;
    expect(changed.ok, JSON.stringify(changed)).toBe(true);
    const revision = changed.data.revision;
    const component = page.locator('.document-page-stack--screen [data-document-node-id="instance"] [data-document-edit-target="true"]').first();
    await component.locator("p").click();
    const editor = page.locator('[data-markdown-editor-host] .ProseMirror'); await expect(editor).toBeFocused();
    await editor.evaluate((element) => { (window as any).outputEditor = element; });
    const cdp = await page.context().newCDPSession(page); await cdp.send("Input.imeSetComposition", { text: "조합", selectionStart: 2, selectionEnd: 2 });
    const preview = await client.callTool({ name: "preview_document", arguments: { documentId: fixture.documentId, expectedRevision: revision } });
    expect((preview.structuredContent as any).ok, JSON.stringify(preview.structuredContent)).toBe(true);
    const metadata = (preview.structuredContent as any).data;
    expect(metadata.pageCount).toBeGreaterThan(1); expect(Math.max(metadata.widthPx, metadata.heightPx)).toBeLessThanOrEqual(2048);
    expect(metadata.warnings.length).toBeGreaterThan(0);
    const image = preview.content.find((content: any) => content.type === "image") as any;
    expect(Buffer.from(image.data, "base64").length).toBeLessThanOrEqual(4 * 1024 * 1024);
    await writeFile(testInfo.outputPath("agent-preview.png"), Buffer.from(image.data, "base64"));
    const pageTwo = await client.callTool({ name: "preview_document", arguments: { documentId: fixture.documentId, expectedRevision: revision, page: 2 } });
    expect((pageTwo.structuredContent as any).ok).toBe(true);
    await writeFile(testInfo.outputPath("agent-preview-page-2.png"), Buffer.from((pageTwo.content.find((content: any) => content.type === "image") as any).data, "base64"));
    const missing = (await client.callTool({ name: "preview_document", arguments: { documentId: fixture.documentId, expectedRevision: revision, page: metadata.pageCount + 1 } })).structuredContent as any;
    expect(missing.error.code).toBe("PAGE_OUT_OF_RANGE");
    const requestId = randomUUID();
    const pending = (await client.callTool({ name: "export_pdf", arguments: { documentId: fixture.documentId, expectedRevision: revision, requestId, filename: "snapshot.pdf" } })).structuredContent as any;
    expect(pending.data.status).toBe("pending");
    let operation: any;
    await expect.poll(async () => { operation = (await client.callTool({ name: "get_operation", arguments: { requestId } })).structuredContent as any; return operation.data?.status; }, { timeout: 65_000 }).toBe("completed");
    expect(operation.data.result.revision).toBe(revision);
    const resource = await client.readResource({ uri: operation.data.result.uri });
    const pdf = Buffer.from((resource.contents[0] as any).blob, "base64");
    expect(pdf.subarray(0, 5).toString()).toBe("%PDF-"); await writeFile(testInfo.outputPath("agent-output.pdf"), pdf);
    await expect(editor).toBeFocused(); expect(await editor.evaluate((element) => element === (window as any).outputEditor)).toBe(true);
    await expect(editor).toContainText("조합");
    expect(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().length)).toBe(1);
    await page.evaluate((id) => window.documents.agentSetGrants(id, { documentIds: [], write: false, create: false, libraryRead: false, render: false }), connection.id);
    await expect(async () => client.readResource({ uri: operation.data.result.uri })).rejects.toThrow();
    const denied = (await client.callTool({ name: "get_operation", arguments: { requestId } })).structuredContent as any; expect(denied.error.code).toBe("NOT_FOUND_OR_DENIED");
    await cdp.send("Input.insertText", { text: "조합" }); await cdp.detach();
  } finally { await client.close(); await app?.close(); await rm(temporary, { recursive: true, force: true }); }
});
